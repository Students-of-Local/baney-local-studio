#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    ClaudeCode,
    Codex,
    Skills,
}

impl Kind {
    #[must_use]
    pub fn label(self) -> &'static str {
        match self {
            Kind::ClaudeCode => "Claude Code",
            Kind::Codex => "Codex",
            Kind::Skills => "Agent Skills",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Translation {
    pub kind: Kind,
    pub manifest: String,
    pub id: String,
    pub name: String,
    pub version: String,
    pub description: String,
    pub icon: Option<String>,
    pub skills: Option<String>,
    pub commands: Vec<Command>,
    pub server: Option<Server>,
    pub not_used: Vec<String>,
    pub findings: Vec<Finding>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Command {
    pub name: String,
    pub description: String,
    pub prompt: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Server {
    pub name: String,
    pub from: String,
    pub original: String,
    run: Run,
    host: BTreeMap<String, String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Run {
    Direct { command: String, args: Vec<String> },
    Launcher { program: Vec<Part>, args: Vec<Vec<Part>>, env: Vec<(String, Vec<Part>)> },
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Part {
    Text(String),
    Root,
    Data,
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Finding {
    pub file: String,
    pub line: usize,
    pub what: String,
    pub text: String,
}

impl Finding {
    #[must_use]
    pub fn key(&self) -> String {
        format!("{}: {}: {}", self.file, self.what, self.text)
    }
}

impl std::fmt::Display for Finding {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        if self.line == 0 {
            write!(formatter, "{}: {}", self.file, self.what)
        } else if self.text.is_empty() {
            write!(formatter, "{}:{}: {}", self.file, self.line, self.what)
        } else {
            write!(formatter, "{}:{}: {}: {}", self.file, self.line, self.what, self.text)
        }
    }
}

impl Translation {
    #[must_use]
    pub fn summary(&self) -> String {
        match self.kind {
            Kind::Skills => format!("A pack of Agent Skills, translated by Local Studio from {}", self.manifest),
            kind => format!("A {} plugin, translated by Local Studio from {}", kind.label(), self.manifest),
        }
    }

    fn uses_launcher(&self) -> bool {
        self.server.as_ref().is_some_and(|server| matches!(server.run, Run::Launcher { .. }))
    }
}

/// The translation an installed plugin came from, or `None` for a native one.
#[must_use]
pub fn report(dir: &Path) -> Option<Translation> {
    let root = dir.parent()?;
    let id = dir.file_name()?.to_str()?;
    let recorded = super::Origins::load(root).ok()?.get(id).is_some_and(|origin| origin.translated);
    checked(dir, recorded)
}

pub(crate) fn checked(dir: &Path, recorded: bool) -> Option<Translation> {
    if !recorded {
        return None;
    }
    let hint = dir.canonicalize().ok()?.file_name()?.to_str()?.to_string();
    let translation = analyze(dir, &hint).ok().flatten()?;
    let written = std::fs::read_to_string(dir.join(MANIFEST)).ok()?;
    if unstamped(&written)? != unstamped(&manifest(&translation))? {
        return None;
    }
    for path in LAUNCHERS {
        let on_disk = std::fs::symlink_metadata(dir.join(path))
            .ok()
            .filter(std::fs::Metadata::is_file)
            .and_then(|_| std::fs::read_to_string(dir.join(path)).ok());
        let expected = if path == LAUNCHER && translation.uses_launcher() { launcher(&translation).ok() } else { None };
        if on_disk != expected {
            return None;
        }
    }
    Some(translation)
}

fn unstamped(text: &str) -> Option<(&str, &str)> {
    let (first, rest) = text.split_once('\n')?;
    let (_, from) = first.strip_prefix(GENERATED)?.split_once(" from ")?;
    Some((from, rest))
}

pub(crate) fn foreign(dir: &Path) -> bool {
    std::fs::symlink_metadata(dir.join(MANIFEST)).is_err()
}

/// Writes `plugin.toml` (and the server launcher, when one is needed) into a scratch copy that has none.
pub(crate) fn translate(dir: &Path, hint: &str) -> Result<Translation, Vec<String>> {
    let studio = dir.join(STUDIO_DIR);
    match std::fs::symlink_metadata(&studio) {
        Ok(meta) if meta.is_dir() => std::fs::remove_dir_all(&studio),
        Ok(_) => std::fs::remove_file(&studio),
        Err(_) => Ok(()),
    }
    .map_err(|error| vec![format!("cannot clear {}: {error}", studio.display())])?;
    let Some(translation) = analyze(dir, hint).map_err(|error| vec![error])? else {
        return Err(vec![nothing_here(dir)]);
    };
    clear_executables(dir, Path::new("")).map_err(|error| vec![error])?;
    if translation.uses_launcher() {
        let text = launcher(&translation).map_err(|error| vec![error])?;
        let path = dir.join(LAUNCHER);
        std::fs::create_dir_all(dir.join(STUDIO_DIR))
            .and_then(|()| std::fs::write(&path, text))
            .map_err(|error| vec![format!("cannot write {}: {error}", path.display())])?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))
                .map_err(|error| vec![format!("cannot write {}: {error}", path.display())])?;
        }
    }
    let path = dir.join(MANIFEST);
    std::fs::write(&path, manifest(&translation))
        .map_err(|error| vec![format!("cannot write {}: {error}", path.display())])?;
    Ok(translation)
}

fn nothing_here(dir: &Path) -> String {
    match super::market::listing(dir) {
        Some(names) if !names.is_empty() => format!(
            "this is a plugin marketplace, not a plugin; it lists {}. Install one with local-studio plugin install <source> --plugin <name>",
            names.join(", ")
        ),
        _ => format!(
            "no {MANIFEST}, {CLAUDE}, {PORTABLE}, {CODEX} or skills/ folder of Agent Skills in {}",
            dir.display()
        ),
    }
}

pub(crate) fn analyze(dir: &Path, hint: &str) -> Result<Option<Translation>, String> {
    if let Some(manifest) = json_object(dir, CLAUDE)? {
        return claude(dir, &manifest).map(Some);
    }
    let portable = json_object(dir, PORTABLE)?.filter(|manifest| portable(dir, manifest));
    let overlay = json_object(dir, CODEX)?;
    if portable.is_some() || overlay.is_some() {
        return codex(dir, portable.as_ref(), overlay.as_ref()).map(Some);
    }
    if !skill_folders(dir, "skills").is_empty() {
        let id = fold(hint);
        if !valid(&id) {
            return Err(format!("cannot make a plugin id from the folder name {hint:?}"));
        }
        return Ok(Some(Translation {
            kind: Kind::Skills,
            manifest: "skills/".to_string(),
            name: id.clone(),
            version: "0.0.0".to_string(),
            description: format!("{id}, a pack of Agent Skills"),
            id,
            icon: None,
            skills: Some("skills".to_string()),
            commands: Vec::new(),
            server: None,
            not_used: Vec::new(),
            findings: Vec::new(),
        }));
    }
    Ok(None)
}

fn portable(dir: &Path, manifest: &Map<String, Value>) -> bool {
    manifest.get("name").and_then(Value::as_str).is_some()
        && (manifest.get("$schema").and_then(Value::as_str).is_some_and(|schema| schema.contains("agent-plugins"))
            || ["skills", "mcpServers", "extensions"].iter().any(|key| manifest.contains_key(*key))
            || dir.join("skills").is_dir()
            || dir.join("mcp.json").is_file())
}

fn valid(id: &str) -> bool {
    super::valid_id(id)
}

#[must_use]
pub fn fold(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.is_empty() && !out.ends_with('-') {
            out.push('-');
        }
    }
    out.trim_end_matches('-').to_string()
}

struct Base {
    kind: Kind,
    manifest: String,
    id: String,
    name: String,
    version: String,
    description: String,
}

fn base(kind: Kind, manifest: &str, fields: &Map<String, Value>, display: Option<&str>) -> Result<Base, String> {
    let name = text(fields, "name").ok_or_else(|| format!("{manifest} has no name"))?;
    let id = fold(&name);
    if !valid(&id) {
        return Err(format!("{manifest}: the name {name:?} leaves no plugin id"));
    }
    let shown = display.map(str::to_string).or_else(|| text(fields, "displayName")).unwrap_or_else(|| name.clone());
    Ok(Base {
        kind,
        manifest: manifest.to_string(),
        id,
        version: text(fields, "version").filter(|version| valid_semver(version)).unwrap_or_else(|| "0.0.0".to_string()),
        description: text(fields, "description").unwrap_or_else(|| format!("{shown}, a {} plugin", kind.label())),
        name: shown,
    })
}

fn claude(dir: &Path, manifest: &Map<String, Value>) -> Result<Translation, String> {
    let base = base(Kind::ClaudeCode, CLAUDE, manifest, None)?;
    let mut not_used: Vec<String> = Vec::new();
    let icon = text(manifest, "icon").and_then(|icon| local_file(dir, &icon));
    let skills = skills(dir, manifest.get("skills"), &mut not_used);
    let mut findings: Vec<Finding> = Vec::new();
    let commands = commands(dir, manifest.get("commands"), &mut not_used, &mut findings);
    let mut configs: Vec<Config> = Vec::new();
    if dir.join(".mcp.json").is_file() {
        servers_in(dir, CLAUDE, &Value::String("./.mcp.json".to_string()), &mut configs, &mut not_used);
    }
    if let Some(value) = manifest.get("mcpServers") {
        servers_in(dir, CLAUDE, value, &mut configs, &mut not_used);
    }
    let server = server(dir, &base.id, configs, &mut not_used);
    let used = server.as_ref().map(|server| runs(dir, server)).unwrap_or_default();
    hooks(dir, manifest.get("hooks"), "hooks/hooks.json", &mut not_used);
    for (key, default, what) in [
        ("agents", "agents", "agent"),
        ("outputStyles", "output-styles", "output style"),
        ("workflows", "workflows", "workflow"),
        ("themes", "themes", "theme"),
    ] {
        let value =
            manifest.get(key).or_else(|| manifest.get("experimental").and_then(|experimental| experimental.get(key)));
        for file in component_files(dir, value, default) {
            not_used.push(format!("{what} {file}: Local Studio does not use Claude Code {what}s"));
        }
    }
    named(
        dir,
        manifest.get("lspServers"),
        ".lsp.json",
        "LSP server",
        "Local Studio runs no LSP servers",
        &mut not_used,
    );
    let monitors = manifest
        .get("experimental")
        .and_then(|experimental| experimental.get("monitors"))
        .or_else(|| manifest.get("monitors"));
    monitors_in(dir, monitors, &mut not_used);
    for file in files_under(dir, "bin") {
        if !used.contains(&file) {
            not_used.push(format!("{file}: Claude Code puts it on the PATH; Local Studio does not"));
        }
    }
    if let Some(Value::Object(options)) = manifest.get("userConfig") {
        for key in options.keys() {
            not_used.push(format!("setting {key} (userConfig): Local Studio does not ask for plugin settings"));
        }
    }
    if let Some(Value::Array(channels)) = manifest.get("channels") {
        for channel in channels {
            let server = channel.get("server").and_then(Value::as_str).unwrap_or("?");
            not_used.push(format!("channel on {server}: Local Studio has no plugin channels"));
        }
    }
    if let Some(Value::Array(dependencies)) = manifest.get("dependencies") {
        for dependency in dependencies {
            let name = dependency.as_str().or_else(|| dependency.get("name").and_then(Value::as_str)).unwrap_or("?");
            not_used.push(format!("needs plugin {name}: Local Studio installs no plugin dependencies"));
        }
    }
    Ok(finish(base, icon, skills, commands, server, not_used, findings))
}

fn codex(
    dir: &Path,
    portable: Option<&Map<String, Value>>,
    overlay: Option<&Map<String, Value>>,
) -> Result<Translation, String> {
    let (manifest, path) = match (portable, overlay) {
        (Some(portable), _) => (portable, PORTABLE),
        (None, Some(overlay)) => (overlay, CODEX),
        (None, None) => return Err("no Codex manifest".to_string()),
    };
    let openai = manifest
        .get("extensions")
        .and_then(|extensions| extensions.get("com.openai"))
        .and_then(Value::as_object)
        .or(overlay);
    let interface = openai.and_then(|openai| openai.get("interface")).and_then(Value::as_object);
    let display = interface.and_then(|interface| interface.get("displayName")).and_then(Value::as_str);
    let base = base(Kind::Codex, path, manifest, display)?;
    let mut not_used: Vec<String> = Vec::new();
    let icon = interface
        .and_then(|interface| interface.get("composerIcon").or_else(|| interface.get("logo")))
        .and_then(Value::as_str)
        .and_then(|icon| local_file(dir, icon));
    let skills = skills(dir, manifest.get("skills"), &mut not_used);
    let mut configs: Vec<Config> = Vec::new();
    if portable.is_some() && dir.join("mcp.json").is_file() {
        servers_in(dir, path, &Value::String("./mcp.json".to_string()), &mut configs, &mut not_used);
    }
    if let Some(value) = manifest.get("mcpServers") {
        servers_in(dir, path, value, &mut configs, &mut not_used);
    }
    let server = server(dir, &base.id, configs, &mut not_used);
    hooks(dir, openai.and_then(|openai| openai.get("hooks")), "hooks/hooks.json", &mut not_used);
    if let Some(apps) = openai.and_then(|openai| openai.get("apps")) {
        let label = apps.as_str().unwrap_or("the manifest");
        not_used.push(format!("apps in {label}: ChatGPT app connections; Local Studio does not connect apps"));
    }
    Ok(finish(base, icon, skills, Vec::new(), server, not_used, Vec::new()))
}

fn finish(
    base: Base,
    icon: Option<String>,
    skills: Option<String>,
    commands: Vec<Command>,
    server: Option<Server>,
    mut not_used: Vec<String>,
    findings: Vec<Finding>,
) -> Translation {
    let mut seen = BTreeSet::new();
    not_used.retain(|item| seen.insert(item.clone()));
    Translation {
        kind: base.kind,
        manifest: base.manifest,
        id: base.id,
        name: base.name,
        version: base.version,
        description: base.description,
        icon,
        skills,
        commands,
        server,
        not_used,
        findings,
    }
}

fn text(fields: &Map<String, Value>, key: &str) -> Option<String> {
    fields.get(key).and_then(Value::as_str).map(str::trim).filter(|value| !value.is_empty()).map(str::to_string)
}

fn read_text(dir: &Path, path: &Path) -> Option<String> {
    instruction(dir, path).ok().flatten()
}

fn json_object(dir: &Path, relative: &str) -> Result<Option<Map<String, Value>>, String> {
    let path = dir.join(relative);
    let Some(text) = read_text(dir, &path) else { return Ok(None) };
    match serde_json::from_str::<Value>(&text) {
        Ok(Value::Object(object)) => Ok(Some(object)),
        Ok(_) => Err(format!("{relative} is not a JSON object")),
        Err(error) => Err(format!("{relative}: {error}")),
    }
}

/// A manifest path made relative to the plugin, or `None` when it is missing or leaves the plugin.
fn local(dir: &Path, path: &str) -> Option<String> {
    let trimmed = path.trim();
    if trimmed.contains('\\') {
        return None;
    }
    let relative = trimmed.strip_prefix("./").unwrap_or(trimmed).trim_end_matches('/');
    let relative = if relative.is_empty() { "." } else { relative };
    let full = inside(dir, relative).ok()?;
    let base = dir.canonicalize().ok()?;
    let real = full.canonicalize().ok()?;
    real.starts_with(&base).then(|| relative.trim_start_matches("./").to_string())
}

fn local_file(dir: &Path, path: &str) -> Option<String> {
    local(dir, path).filter(|relative| dir.join(relative).is_file())
}

fn local_dir(dir: &Path, path: &str) -> Option<String> {
    local(dir, path).filter(|relative| dir.join(relative).is_dir())
}

fn paths(value: Option<&Value>) -> Vec<String> {
    match value {
        Some(Value::String(path)) => vec![path.clone()],
        Some(Value::Array(items)) => items.iter().filter_map(Value::as_str).map(str::to_string).collect(),
        _ => Vec::new(),
    }
}

fn skill_folders(dir: &Path, relative: &str) -> Vec<String> {
    sorted(&dir.join(relative))
        .into_iter()
        .filter(|path| path.join("SKILL.md").is_file())
        .filter_map(|path| path.file_name().and_then(|name| name.to_str()).map(str::to_string))
        .collect()
}

fn skills(dir: &Path, listed: Option<&Value>, not_used: &mut Vec<String>) -> Option<String> {
    let mut candidates: Vec<String> = Vec::new();
    if dir.join("skills").is_dir() {
        candidates.push("skills".to_string());
    }
    for path in paths(listed) {
        match local_dir(dir, &path) {
            Some(relative) if relative == "." => {
                not_used
                    .push(format!("skills at {path}: Local Studio reads skills only from a folder of skill folders"));
            }
            Some(relative) if !candidates.contains(&relative) => candidates.push(relative),
            Some(_) => {}
            None => not_used.push(format!("skills at {path}: missing or outside the plugin")),
        }
    }
    let mut candidates = candidates.into_iter();
    let chosen = candidates.next();
    for extra in candidates {
        not_used.push(format!(
            "skills in {extra}: Local Studio reads one skills folder, {}",
            chosen.as_deref().unwrap_or("")
        ));
    }
    chosen
}

fn sorted(dir: &Path) -> Vec<PathBuf> {
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|entries| entries.filter_map(Result::ok).map(|entry| entry.path()).collect())
        .unwrap_or_default();
    entries.sort();
    entries
}

fn relative_to(dir: &Path, path: &Path) -> String {
    path.strip_prefix(dir).unwrap_or(path).to_string_lossy().replace('\\', "/")
}

fn files_under(dir: &Path, relative: &str) -> Vec<String> {
    let mut found: Vec<String> = Vec::new();
    let mut pending = vec![dir.join(relative)];
    while let Some(folder) = pending.pop() {
        for path in sorted(&folder) {
            match std::fs::symlink_metadata(&path) {
                Ok(meta) if meta.is_dir() => pending.push(path),
                Ok(_) => found.push(relative_to(dir, &path)),
                Err(_) => {}
            }
        }
    }
    found.sort();
    found
}

fn component_files(dir: &Path, listed: Option<&Value>, default: &str) -> Vec<String> {
    let roots: Vec<String> = match listed {
        None => vec![default.to_string()],
        Some(value) => paths(Some(value)),
    };
    let mut files: Vec<String> = Vec::new();
    for root in roots {
        match local(dir, &root) {
            Some(relative) if dir.join(&relative).is_dir() => files.extend(files_under(dir, &relative)),
            Some(relative) => files.push(relative),
            None if listed.is_some() => files.push(root),
            None => {}
        }
    }
    files
}

fn commands(
    dir: &Path,
    listed: Option<&Value>,
    not_used: &mut Vec<String>,
    findings: &mut Vec<Finding>,
) -> Vec<Command> {
    let mut sources: Vec<(Option<String>, String, Option<String>)> = Vec::new();
    match listed {
        None => {
            for file in files_under(dir, "commands") {
                sources.push((None, file, None));
            }
        }
        Some(Value::Object(map)) => {
            for (name, entry) in map {
                let description = entry.get("description").and_then(Value::as_str).map(str::to_string);
                match entry.get("source").and_then(Value::as_str) {
                    Some(source) => match local_file(dir, source) {
                        Some(file) => sources.push((Some(name.clone()), file, description)),
                        None => not_used.push(format!("command {name}: {source} is missing or outside the plugin")),
                    },
                    None => not_used.push(format!(
                        "command {name}: its text is inline in the manifest; Local Studio reads commands from files"
                    )),
                }
            }
        }
        Some(value) => {
            for path in paths(Some(value)) {
                match local(dir, &path) {
                    Some(relative) if dir.join(&relative).is_dir() => {
                        for file in files_under(dir, &relative) {
                            sources.push((None, file, None));
                        }
                    }
                    Some(relative) => sources.push((None, relative, None)),
                    None => not_used.push(format!("commands at {path}: missing or outside the plugin")),
                }
            }
        }
    }
    let mut commands: Vec<Command> = Vec::new();
    for (name, file, description) in sources {
        if !has_extension(&file, "md") {
            continue;
        }
        let name = name.unwrap_or_else(|| {
            Path::new(&file).file_stem().and_then(|stem| stem.to_str()).unwrap_or_default().to_string()
        });
        let default_dir = listed.is_none() && file.matches('/').count() > 1;
        if default_dir {
            not_used.push(format!("command {file}: Local Studio reads commands only from the top of commands/"));
            continue;
        }
        if !valid_command_name(&name) {
            not_used.push(format!("command {file}: {name:?} is not a command name Local Studio takes"));
            continue;
        }
        if commands.iter().any(|command| command.name == name) {
            not_used.push(format!("command {file}: another command is already named {name}"));
            continue;
        }
        let content = match instruction(dir, &dir.join(&file)) {
            Ok(content) => content.unwrap_or_default(),
            Err(reason) => {
                not_used.push(format!("command {file}: {reason}"));
                continue;
            }
        };
        for (index, line) in content.lines().enumerate() {
            for ran in shell_lines(line) {
                findings.push(Finding {
                    file: file.clone(),
                    line: index + 1,
                    what: format!("runs `{ran}` in Claude Code; Local Studio sends it as text"),
                    text: String::new(),
                });
            }
        }
        let description = description
            .or_else(|| frontmatter::field(&content, "description"))
            .or_else(|| {
                frontmatter::strip(&content)
                    .lines()
                    .map(str::trim)
                    .find(|line| !line.is_empty())
                    .map(|line| line.chars().take(120).collect())
            })
            .unwrap_or_else(|| format!("{name} command"));
        commands.push(Command { name, description, prompt: file });
    }
    commands
}

fn has_extension(path: &str, wanted: &str) -> bool {
    Path::new(path).extension().is_some_and(|ext| ext.eq_ignore_ascii_case(wanted))
}

fn shell_lines(line: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut rest = line;
    while let Some(start) = rest.find("!`") {
        let after = &rest[start + 2..];
        let Some(end) = after.find('`') else { break };
        let ran = after[..end].trim();
        if !ran.is_empty() {
            found.push(ran.to_string());
        }
        rest = &after[end + 1..];
    }
    found
}

fn hooks(dir: &Path, listed: Option<&Value>, default: &str, not_used: &mut Vec<String>) {
    let mut sources: Vec<(String, Value)> = Vec::new();
    if let Ok(Some(object)) = json_object(dir, default) {
        sources.push((default.to_string(), Value::Object(object)));
    }
    let items: Vec<Value> = match listed {
        Some(Value::Array(items)) => items.clone(),
        Some(value) => vec![value.clone()],
        None => Vec::new(),
    };
    for item in items {
        match &item {
            Value::String(path) => match local_file(dir, path) {
                Some(relative) if relative == default => {}
                Some(relative) => match json_object(dir, &relative) {
                    Ok(Some(object)) => sources.push((relative, Value::Object(object))),
                    _ => not_used.push(format!("hooks in {relative}: Local Studio never runs hooks")),
                },
                None => not_used.push(format!("hooks at {path}: Local Studio never runs hooks")),
            },
            other => sources.push(("the manifest".to_string(), other.clone())),
        }
    }
    for (from, value) in sources {
        let events = value.get("hooks").cloned().unwrap_or(value);
        let mut listed_any = false;
        if let Value::Object(events) = events {
            for (event, groups) in events {
                for group in groups.as_array().into_iter().flatten() {
                    for handler in group.get("hooks").and_then(Value::as_array).into_iter().flatten() {
                        let what = handler
                            .get("command")
                            .and_then(Value::as_str)
                            .map(|command| format!("runs `{command}`"))
                            .or_else(|| {
                                handler.get("type").and_then(Value::as_str).map(|kind| format!("a {kind} hook"))
                            })
                            .unwrap_or_else(|| "a hook".to_string());
                        not_used.push(format!("hook {event} in {from} {what}: Local Studio never runs hooks"));
                        listed_any = true;
                    }
                }
            }
        }
        if !listed_any {
            not_used.push(format!("hooks in {from}: Local Studio never runs hooks"));
        }
    }
}

fn named(dir: &Path, listed: Option<&Value>, default: &str, what: &str, why: &str, not_used: &mut Vec<String>) {
    let mut names: Vec<String> = Vec::new();
    let add = |value: &Value, names: &mut Vec<String>| match value {
        Value::Object(map) => names.extend(map.keys().cloned()),
        Value::String(path) => match local_file(dir, path).map(|relative| json_object(dir, &relative)) {
            Some(Ok(Some(map))) => names.extend(map.keys().cloned()),
            _ => names.push(path.clone()),
        },
        _ => {}
    };
    if let Ok(Some(map)) = json_object(dir, default) {
        add(&Value::Object(map), &mut names);
    }
    match listed {
        Some(Value::Array(items)) => items.iter().for_each(|item| add(item, &mut names)),
        Some(value) => add(value, &mut names),
        None => {}
    }
    for name in names {
        not_used.push(format!("{what} {name}: {why}"));
    }
}

fn monitors_in(dir: &Path, listed: Option<&Value>, not_used: &mut Vec<String>) {
    let items: Vec<Value> = match listed {
        Some(Value::Array(items)) => items.clone(),
        Some(Value::String(path)) => match local_file(dir, path) {
            Some(relative) => read_text(dir, &dir.join(relative))
                .and_then(|text| serde_json::from_str::<Value>(&text).ok())
                .and_then(|value| value.as_array().cloned())
                .unwrap_or_else(|| vec![Value::String(path.clone())]),
            None => vec![Value::String(path.clone())],
        },
        _ => read_text(dir, &dir.join("monitors/monitors.json"))
            .and_then(|text| serde_json::from_str::<Value>(&text).ok())
            .and_then(|value| value.as_array().cloned())
            .unwrap_or_default(),
    };
    for item in items {
        let label = item
            .get("name")
            .and_then(Value::as_str)
            .or_else(|| item.get("command").and_then(Value::as_str))
            .or_else(|| item.as_str())
            .unwrap_or("?");
        not_used.push(format!("monitor {label}: Local Studio runs no monitors"));
    }
}

type Config = (String, String, Map<String, Value>);

fn runs(dir: &Path, server: &Server) -> BTreeSet<String> {
    match &server.run {
        Run::Direct { command, .. } => std::iter::once(command.clone()).collect(),
        Run::Launcher { program, args, .. } => {
            std::iter::once(program).chain(args).filter_map(|parts| file_in(dir, parts, ".")).collect()
        }
    }
}

fn servers_in(dir: &Path, manifest: &str, value: &Value, configs: &mut Vec<Config>, not_used: &mut Vec<String>) {
    let mut add = |name: &str, from: &str, config: &Value, configs: &mut Vec<Config>| {
        let Some(config) = config.as_object() else {
            not_used.push(format!("MCP server {name}: its entry is not a JSON object"));
            return;
        };
        configs.retain(|(other, _, _)| other != name);
        configs.push((name.to_string(), from.to_string(), config.clone()));
    };
    match value {
        Value::String(path) => {
            if has_extension(path, "mcpb") || has_extension(path, "dxt") || path.contains("://") {
                not_used.push(format!("MCP bundle {path}: Local Studio does not unpack or download bundles"));
                return;
            }
            let Some(relative) = local_file(dir, path) else {
                not_used.push(format!("MCP servers in {path}: missing, outside the plugin or not JSON"));
                return;
            };
            let Ok(Some(object)) = json_object(dir, &relative) else {
                not_used.push(format!("MCP servers in {path}: missing, outside the plugin or not JSON"));
                return;
            };
            let servers = match object.get("mcpServers") {
                Some(Value::Object(servers)) => servers.clone(),
                _ => object,
            };
            for (name, config) in &servers {
                add(name, &relative, config, configs);
            }
        }
        Value::Object(servers) => {
            for (name, config) in servers {
                add(name, manifest, config, configs);
            }
        }
        Value::Array(items) => {
            for item in items {
                servers_in(dir, manifest, item, configs, not_used);
            }
        }
        _ => {}
    }
}

fn server(dir: &Path, id: &str, configs: Vec<Config>, not_used: &mut Vec<String>) -> Option<Server> {
    if configs.len() > 1 {
        for (name, _, _) in &configs {
            not_used.push(format!(
                "MCP server {name}: the plugin has {} servers, and Local Studio sets up a plugin's server only when it has one",
                configs.len()
            ));
        }
        return None;
    }
    let (name, from, config) = configs.into_iter().next()?;
    match one_server(dir, id, &name, &from, &config) {
        Ok(server) => Some(server),
        Err(reason) => {
            not_used.push(format!("MCP server {name}: {reason}"));
            None
        }
    }
}

fn parts(text: &str) -> Result<Vec<Part>, String> {
    let mut parts: Vec<Part> = Vec::new();
    let mut rest = text;
    let mut literal = String::new();
    while let Some(start) = rest.find("${") {
        literal.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let end = after.find('}').ok_or_else(|| format!("{text:?} has an unclosed ${{"))?;
        let part = match &after[..end] {
            "CLAUDE_PLUGIN_ROOT" | "PLUGIN_ROOT" => Part::Root,
            "CLAUDE_PLUGIN_DATA" | "PLUGIN_DATA" => Part::Data,
            other => return Err(format!("{text:?} uses ${{{other}}}, which Local Studio cannot fill in")),
        };
        if !literal.is_empty() {
            parts.push(Part::Text(std::mem::take(&mut literal)));
        }
        parts.push(part);
        rest = &after[end + 1..];
    }
    literal.push_str(rest);
    if !literal.is_empty() {
        parts.push(Part::Text(literal));
    }
    Ok(parts)
}

fn plain(parts: &[Part]) -> Option<&str> {
    match parts {
        [] => Some(""),
        [Part::Text(text)] => Some(text),
        _ => None,
    }
}

fn file_in(dir: &Path, parts: &[Part], base: &str) -> Option<String> {
    let relative = match parts {
        [Part::Root, Part::Text(rest)] => rest.strip_prefix('/')?.to_string(),
        [Part::Text(text)] if !Path::new(text).is_absolute() && !text.starts_with('-') => {
            let text = text.strip_prefix("./").unwrap_or(text);
            if base == "." {
                text.to_string()
            } else {
                format!("{base}/{text}")
            }
        }
        _ => return None,
    };
    local_file(dir, &relative)
}

fn dir_in(dir: &Path, parts: &[Part]) -> Option<String> {
    match parts {
        [Part::Root] => Some(".".to_string()),
        [Part::Root, Part::Text(rest)] => local_dir(dir, rest.trim_start_matches('/')),
        [Part::Text(text)] if !Path::new(text).is_absolute() => local_dir(dir, text),
        _ => None,
    }
}

fn shebang(dir: &Path, relative: &str) -> Option<String> {
    let text = read_text(dir, &dir.join(relative))?;
    let line = text.lines().next()?.strip_prefix("#!")?.trim();
    let mut words = line.split_whitespace();
    let first = words.next()?;
    let program = if first.ends_with("/env") { words.find(|word| !word.starts_with('-'))? } else { first };
    let program = program.rsplit('/').next()?;
    ["node", "python3", "python", "bun", "deno"].contains(&program).then(|| program.to_string())
}

fn one_server(dir: &Path, id: &str, name: &str, from: &str, config: &Map<String, Value>) -> Result<Server, String> {
    let kind = config.get("type").and_then(Value::as_str).unwrap_or("stdio");
    if let Some(url) = config.get("url").and_then(Value::as_str) {
        return Err(format!("a remote server at {url}; the tree hash can't cover what it runs"));
    }
    if kind != "stdio" {
        return Err(format!("a remote server ({kind}); the tree hash can't cover what it runs"));
    }
    let command = config.get("command").and_then(Value::as_str).ok_or_else(|| "it names no command".to_string())?;
    let args: Vec<String> = match config.get("args") {
        None => Vec::new(),
        Some(Value::Array(items)) => items
            .iter()
            .map(|item| item.as_str().map(str::to_string))
            .collect::<Option<_>>()
            .ok_or_else(|| "its args are not all text".to_string())?,
        Some(_) => return Err("its args are not a list".to_string()),
    };
    if let Some(cwd) = config.get("cwd").and_then(Value::as_str) {
        if !matches!(cwd, "${CLAUDE_PLUGIN_ROOT}" | "${PLUGIN_ROOT}" | "." | "./") {
            return Err(format!("it sets its own working folder ({cwd})"));
        }
    }
    let declared = std::iter::once(command.to_string()).chain(args.iter().cloned()).collect::<Vec<_>>();
    let command_parts = parts(command)?;
    let arg_parts: Vec<Vec<Part>> = args.iter().map(|arg| parts(arg)).collect::<Result<_, _>>()?;
    let (program, launch_args, direct) = match plain(&command_parts) {
        Some(word) if !word.contains('/') && !word.contains('\\') => {
            let word = word.to_string();
            if FETCHERS.contains(&word.as_str()) {
                return Err(format!("it runs {word}, which fetches or runs code the tree hash can't cover"));
            }
            let (program, launch_args) = interpreted(dir, &word, arg_parts)?;
            (program, launch_args, None)
        }
        _ => {
            let relative = file_in(dir, &command_parts, ".")
                .filter(|_| !matches!(command_parts.as_slice(), [Part::Text(text)] if !text.starts_with("./")))
                .ok_or_else(|| format!("it runs {command}, which is not a file inside the plugin"))?;
            let executable =
                std::fs::metadata(dir.join(&relative)).is_ok_and(|meta| crate::platform::is_executable(&meta));
            if relative.starts_with("bin/") && executable {
                let program = vec![Part::Root, Part::Text(format!("/{relative}"))];
                (program, arg_parts, Some(relative))
            } else if let Some(interpreter) = shebang(dir, &relative) {
                let mut file = vec![vec![Part::Root, Part::Text(format!("/{relative}"))]];
                file.extend(arg_parts);
                let (program, launch_args) = interpreted(dir, &interpreter, file)?;
                (program, launch_args, None)
            } else {
                return Err(format!(
                    "it runs {relative}, which is outside bin/ and names no interpreter Local Studio can start"
                ));
            }
        }
    };
    let (host, env, exports) = server_env(id, config)?;
    let original = exports.into_iter().chain(declared).collect::<Vec<_>>().join(" ");
    let run = match direct {
        Some(command) if env.is_empty() && launch_args.iter().all(|arg| plain(arg).is_some()) => {
            Run::Direct { command, args: launch_args.iter().filter_map(|arg| plain(arg).map(str::to_string)).collect() }
        }
        _ => Run::Launcher { program, args: launch_args, env },
    };
    let server = Server { name: name.to_string(), from: from.to_string(), original, run, host };
    if matches!(server.run, Run::Launcher { .. }) {
        render(&server, id, cfg!(windows))?;
    }
    Ok(server)
}

type Env = (BTreeMap<String, String>, Vec<(String, Vec<Part>)>, Vec<String>);

fn server_env(id: &str, config: &Map<String, Value>) -> Result<Env, String> {
    let prefix = env_prefix(id);
    let mut host: BTreeMap<String, String> = BTreeMap::new();
    let mut env: Vec<(String, Vec<Part>)> = Vec::new();
    let mut exports: Vec<String> = Vec::new();
    for (key, value) in config.get("env").and_then(Value::as_object).into_iter().flatten() {
        let value = value.as_str().ok_or_else(|| format!("env {key} is not text"))?;
        if !valid_env_name(key) {
            return Err(format!("env {key} is not a name Local Studio passes (capitals, digits and _)"));
        }
        if [CALLER_ENV, CALLER_NAME_ENV].contains(&key.as_str()) {
            return Err(format!("it sets {key}, which Local Studio sets itself"));
        }
        if LOADER_ENV.contains(&key.as_str()) || LOADER_ENV_PREFIXES.iter().any(|prefix| key.starts_with(prefix)) {
            return Err(format!(
                "it sets {key}, which changes what code starts with it, and the tree hash can't cover that"
            ));
        }
        let reference = value
            .strip_prefix("${")
            .and_then(|rest| rest.strip_suffix('}'))
            .filter(|inner| inner.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !inner.is_empty())
            .filter(|inner| {
                !matches!(*inner, "CLAUDE_PLUGIN_ROOT" | "PLUGIN_ROOT" | "CLAUDE_PLUGIN_DATA" | "PLUGIN_DATA")
            });
        if let Some(inner) = reference {
            host.insert(key.clone(), format!("{prefix}{}", inner.to_ascii_uppercase()));
        } else {
            env.push((key.clone(), parts(value)?));
            exports.push(format!("{key}={value}"));
        }
    }
    Ok((host, env, exports))
}

type Launch = (Vec<Part>, Vec<Vec<Part>>);

fn interpreted(dir: &Path, program: &str, mut args: Vec<Vec<Part>>) -> Result<Launch, String> {
    let text = |part: &Vec<Part>| plain(part).map(str::to_string);
    let no_file = || format!("{program} runs no file inside the plugin");
    match program {
        "node" | "python" | "python3" | "bun" => {
            args.first().and_then(|first| file_in(dir, first, ".")).ok_or_else(no_file)?;
            if program == "bun" {
                args.insert(0, vec![Part::Text("--no-install".to_string())]);
            }
        }
        "deno" => {
            if args.first().and_then(text).as_deref() != Some("run") {
                return Err("deno runs something other than deno run".to_string());
            }
            let mut index = 1;
            while let Some(flag) = args.get(index).and_then(text).filter(|arg| arg.starts_with('-')) {
                if !(flag.starts_with("--allow-") || matches!(flag.as_str(), "-A" | "-q" | "--quiet")) {
                    return Err(format!("deno run {flag} is not a flag Local Studio passes"));
                }
                index += 1;
            }
            args.get(index).and_then(|file| file_in(dir, file, ".")).ok_or_else(no_file)?;
            args.insert(1, vec![Part::Text("--no-remote".to_string())]);
            args.insert(2, vec![Part::Text("--no-npm".to_string())]);
        }
        "uv" => uv(dir, &mut args)?,
        other => {
            return Err(format!(
                "it runs {other} from your PATH, which the tree hash can't cover (Local Studio starts node, python3, python, bun, deno or uv)"
            ))
        }
    }
    Ok((vec![Part::Text(program.to_string())], args))
}

fn uv(dir: &Path, args: &mut Vec<Vec<Part>>) -> Result<(), String> {
    let text = |part: &Vec<Part>| plain(part).map(str::to_string);
    let mut project: Option<String> = None;
    let mut working: Option<String> = None;
    let mut frozen = false;
    let mut index = 0;
    let mut run_at: Option<usize> = None;
    while index < args.len() {
        let word = text(&args[index]);
        match word.as_deref() {
            Some("run") if run_at.is_none() => run_at = Some(index),
            Some("--project" | "--directory") => {
                let folder = args
                    .get(index + 1)
                    .and_then(|folder| dir_in(dir, folder))
                    .ok_or_else(|| "uv names a project folder outside the plugin".to_string())?;
                if word.as_deref() == Some("--directory") {
                    working = Some(folder.clone());
                }
                project = Some(folder);
                index += 1;
            }
            Some(flag) if flag.starts_with("--project=") => {
                let folder = dir_in(dir, &[Part::Text(flag["--project=".len()..].to_string())])
                    .ok_or_else(|| "uv names a project folder outside the plugin".to_string())?;
                project = Some(folder);
            }
            Some("--frozen") => frozen = true,
            Some("--locked" | "--no-dev" | "-q" | "--quiet" | "--offline" | "--no-sync") => {}
            Some(flag) if flag.starts_with('-') => return Err(format!("uv {flag} is not a flag Local Studio passes")),
            _ if run_at.is_some() => break,
            _ => return Err("uv runs something other than uv run".to_string()),
        }
        index += 1;
    }
    let run_at = run_at.ok_or_else(|| "uv runs something other than uv run".to_string())?;
    let project = project.or_else(|| working.clone()).unwrap_or_else(|| ".".to_string());
    if !dir.join(&project).join("uv.lock").is_file() {
        return Err(format!("uv without a uv.lock in {project} fetches packages the tree hash can't cover"));
    }
    let base = working.unwrap_or_else(|| ".".to_string());
    let first = args.get(index).ok_or_else(|| "uv run names nothing to run".to_string())?;
    let runs_file = file_in(dir, first, &base).is_some();
    let runs_python = matches!(text(first).as_deref(), Some("python" | "python3"))
        && args
            .get(index + 1)
            .is_some_and(|next| file_in(dir, next, &base).is_some() || text(next).as_deref() == Some("-m"));
    if !runs_file && !runs_python {
        return Err("uv run runs no file inside the plugin".to_string());
    }
    let mut extra = vec![vec![Part::Text("--no-python-downloads".to_string())]];
    if !frozen && !args.iter().any(|arg| text(arg).as_deref() == Some("--locked")) {
        extra.insert(0, vec![Part::Text("--locked".to_string())]);
    }
    for (offset, part) in extra.into_iter().enumerate() {
        args.insert(run_at + 1 + offset, part);
    }
    Ok(())
}

fn sh_word(parts: &[Part]) -> String {
    if parts.is_empty() {
        return "''".to_string();
    }
    parts
        .iter()
        .map(|part| match part {
            Part::Text(text) => format!("'{}'", text.replace('\'', "'\\''")),
            Part::Root => "\"$root\"".to_string(),
            Part::Data => "\"$data\"".to_string(),
        })
        .collect()
}

fn cmd_word(parts: &[Part]) -> Result<String, String> {
    let mut word = String::from("\"");
    for part in parts {
        match part {
            Part::Text(text) => {
                if let Some(bad) = text.chars().find(|c| !(c.is_ascii_alphanumeric() || " _-./:=,@+".contains(*c))) {
                    return Err(format!(
                        "{text:?} holds {bad:?}, which Local Studio can't write safely into a Windows launcher"
                    ));
                }
                word.push_str(&text.replace('/', "\\"));
            }
            Part::Root => word.push_str("%root%"),
            Part::Data => word.push_str("%data%"),
        }
    }
    word.push('"');
    Ok(word)
}

fn render(server: &Server, id: &str, windows: bool) -> Result<String, String> {
    let Run::Launcher { program, args, env } = &server.run else { return Err("no launcher".to_string()) };
    let data = std::iter::once(program)
        .chain(args)
        .chain(env.iter().map(|(_, value)| value))
        .any(|parts| parts.contains(&Part::Data));
    let mut text = String::new();
    if windows {
        text.push_str("@echo off\r\nsetlocal\r\nfor %%I in (\"%~dp0..\") do set \"root=%%~fI\"\r\n");
        if data {
            let _ = write!(
                text,
                "for %%I in (\"%root%\\..\\..\") do set \"data=%%~fI\\plugin-data\\{id}\"\r\nif not exist \"%data%\" mkdir \"%data%\"\r\n"
            );
        }
        for (key, value) in env {
            let value = cmd_word(value)?;
            let _ = write!(text, "set {key}={}\r\n", &value[1..value.len() - 1]);
        }
        let words: Vec<String> =
            std::iter::once(program).chain(args).map(|parts| cmd_word(parts)).collect::<Result<_, _>>()?;
        let _ = write!(text, "{} %*\r\n", words.join(" "));
    } else {
        text.push_str("#!/bin/sh\nroot=$(CDPATH= cd -- \"$(dirname -- \"$0\")/..\" && pwd -P) || exit 1\n");
        if data {
            let _ = write!(
                text,
                "data=$(CDPATH= cd -- \"$root/../..\" && pwd -P)/plugin-data/{id} || exit 1\nmkdir -p \"$data\" || exit 1\n"
            );
        }
        for (key, value) in env {
            let _ = writeln!(text, "export {key}={}", sh_word(value));
        }
        let words: Vec<String> = std::iter::once(program).chain(args).map(|parts| sh_word(parts)).collect();
        let _ = writeln!(text, "exec {} \"$@\"", words.join(" "));
    }
    Ok(text)
}

fn launcher(translation: &Translation) -> Result<String, String> {
    let server = translation.server.as_ref().ok_or_else(|| "no server".to_string())?;
    render(server, &translation.id, cfg!(windows))
}

fn quoted(text: &str) -> String {
    toml::Value::String(text.to_string()).to_string()
}

fn manifest(translation: &Translation) -> String {
    let mut lines: Vec<String> = vec![
        format!("{GENERATED}{} from {}. Do not edit; reinstall instead.", crate::VERSION, translation.manifest),
        format!("id = {}", quoted(&translation.id)),
        format!("name = {}", quoted(&translation.name)),
        format!("version = {}", quoted(&translation.version)),
        format!("description = {}", quoted(&translation.description)),
    ];
    if let Some(icon) = &translation.icon {
        lines.push(format!("icon = {}", quoted(icon)));
    }
    if let Some(skills) = &translation.skills {
        lines.push(format!("skills = {}", quoted(skills)));
    }
    if translation.server.is_some() {
        lines.push("capabilities = [\"mcp-server\"]".to_string());
    }
    for command in &translation.commands {
        lines.push(String::new());
        lines.push("[[commands]]".to_string());
        lines.push(format!("name = {}", quoted(&command.name)));
        lines.push(format!("description = {}", quoted(&command.description)));
        lines.push(format!("prompt = {}", quoted(&command.prompt)));
    }
    if let Some(server) = &translation.server {
        lines.push(String::new());
        lines.push("[mcp]".to_string());
        match &server.run {
            Run::Direct { command, args } => {
                lines.push(format!("command = {}", quoted(command)));
                if !args.is_empty() {
                    let args: Vec<String> = args.iter().map(|arg| quoted(arg)).collect();
                    lines.push(format!("args = [{}]", args.join(", ")));
                }
            }
            Run::Launcher { .. } => lines.push(format!("command = {}", quoted(LAUNCHER))),
        }
        if !server.host.is_empty() {
            let env: Vec<String> = server.host.iter().map(|(key, host)| format!("{key} = {}", quoted(host))).collect();
            lines.push(format!("env = {{ {} }}", env.join(", ")));
        }
    }
    lines.push(String::new());
    lines.join("\n")
}

fn clear_executables(dir: &Path, relative: &Path) -> Result<(), String> {
    for path in sorted(&dir.join(relative)) {
        let meta = std::fs::symlink_metadata(&path).map_err(|error| format!("{}: {error}", path.display()))?;
        let inner = path.strip_prefix(dir).unwrap_or(&path).to_path_buf();
        if meta.is_dir() {
            if inner != Path::new("bin") {
                clear_executables(dir, &inner)?;
            }
        } else if meta.is_file() && crate::platform::is_executable(&meta) {
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o644))
                    .map_err(|error| format!("cannot clear the executable bit on {}: {error}", path.display()))?;
            }
        }
    }
    Ok(())
}

/// Lines in a plugin's instructions that tell someone to run risky commands, with the file and line.
#[must_use]
pub fn text_findings(plugin: &Plugin) -> Vec<Finding> {
    let base = plugin.dir.canonicalize().unwrap_or_else(|_| plugin.dir.clone());
    let mut files: BTreeSet<PathBuf> = BTreeSet::new();
    let mut seen: BTreeSet<PathBuf> = BTreeSet::new();
    for skill in &plugin.skills {
        if let Some(folder) = skill.path.parent() {
            markdown_under(&base, folder, &mut files, &mut seen);
        }
        files.insert(skill.path.clone());
    }
    files.extend(plugin.prompts.iter().map(|prompt| prompt.path.clone()));
    for command in &plugin.commands {
        if let CommandTarget::Prompt(path) = &command.target {
            files.insert(path.clone());
        }
    }
    files.extend(plugin.skipped.iter().cloned());
    let mut findings: Vec<Finding> = Vec::new();
    for path in files {
        let file = label(&plugin.dir, &base, &path);
        let content = match instruction(&plugin.dir, &path) {
            Ok(Some(content)) => content,
            Ok(None) => continue,
            Err(reason) => {
                findings.push(Finding { file, line: 0, what: reason, text: String::new() });
                continue;
            }
        };
        for (index, line) in content.lines().enumerate() {
            let reasons = reasons(line);
            if !reasons.is_empty() {
                let text: String = line.trim().chars().take(200).collect();
                findings.push(Finding { file: file.clone(), line: index + 1, what: reasons.join(", "), text });
            }
        }
    }
    findings
}

fn label(dir: &Path, base: &Path, path: &Path) -> String {
    let file = relative_to(dir, path);
    if !std::fs::symlink_metadata(path).is_ok_and(|meta| meta.file_type().is_symlink()) {
        return file;
    }
    match path.canonicalize().ok().and_then(|real| real.strip_prefix(base).ok().map(Path::to_path_buf)) {
        Some(real) => format!("{file} -> {}", real.to_string_lossy().replace('\\', "/")),
        None => file,
    }
}

fn markdown_under(base: &Path, folder: &Path, files: &mut BTreeSet<PathBuf>, seen: &mut BTreeSet<PathBuf>) {
    if let Ok(real) = folder.canonicalize() {
        if !seen.insert(real) {
            return;
        }
    }
    for path in sorted(folder) {
        let Ok(meta) = std::fs::symlink_metadata(&path) else { continue };
        let markdown = path.extension().is_some_and(|ext| ext.eq_ignore_ascii_case("md"));
        if meta.is_dir() {
            markdown_under(base, &path, files, seen);
        } else if meta.file_type().is_symlink() {
            match path.canonicalize() {
                Ok(real) if real.is_dir() && real.starts_with(base) => markdown_under(base, &path, files, seen),
                Ok(real) if real.is_dir() => {
                    files.insert(path);
                }
                _ if markdown => {
                    files.insert(path);
                }
                _ => {}
            }
        } else if meta.is_file() && markdown {
            files.insert(path);
        }
    }
}

fn tokens(text: &str) -> Vec<String> {
    text.split_whitespace()
        .map(|token| {
            token.trim_matches(|c: char| matches!(c, '"' | '\'' | '`' | '(' | ')' | ';' | '{' | '}')).to_string()
        })
        .filter(|token| !token.is_empty())
        .collect()
}

fn program_of(segment: &str) -> Option<String> {
    let words = tokens(segment);
    let mut iter = words.iter().map(|word| word.rsplit('/').next().unwrap_or(word).to_string());
    loop {
        let word = iter.next()?;
        if word == "sudo" || word == "env" || word.starts_with('-') || word.contains('=') {
            continue;
        }
        return Some(word.trim_end_matches(".exe").to_string());
    }
}

fn segments(line: &str) -> Vec<String> {
    let mut parts: Vec<String> = Vec::new();
    let mut current = String::new();
    let chars: Vec<char> = line.chars().collect();
    let mut index = 0;
    while index < chars.len() {
        if chars[index] == '|' {
            if chars.get(index + 1) == Some(&'|') {
                current.push_str("||");
                index += 2;
                continue;
            }
            parts.push(std::mem::take(&mut current));
        } else {
            current.push(chars[index]);
        }
        index += 1;
    }
    parts.push(current);
    parts
}

fn has_word(words: &[String], wanted: &[&str]) -> bool {
    words.iter().any(|word| {
        let word = word.rsplit('/').next().unwrap_or(word).trim_end_matches(".exe");
        wanted.contains(&word)
    })
}

fn reasons(line: &str) -> Vec<&'static str> {
    let lower = line.to_ascii_lowercase().replace('\\', "/");
    let words = tokens(&lower);
    let parts = segments(&lower);
    let piped_into_shell = |source: &dyn Fn(&str) -> bool| {
        parts.iter().enumerate().skip(1).any(|(index, part)| {
            program_of(part).is_some_and(|program| SHELLS.contains(&program.as_str()))
                && parts[..index].iter().any(|earlier| source(earlier))
        })
    };
    let downloads = |text: &str| {
        has_word(&tokens(text), &["curl", "wget", "irm", "iwr", "invoke-webrequest", "invoke-restmethod"])
            || text.contains("downloadstring(")
    };
    let mut reasons: Vec<&'static str> = Vec::new();
    let fed = ["<(curl", "<(wget", "< <(curl", "<(iwr"].iter().any(|pattern| lower.contains(pattern))
        || (["$(curl", "$(wget", "`curl", "`wget"].iter().any(|pattern| lower.contains(pattern))
            && (has_word(&words, &["eval"]) || [" -c "].iter().any(|flag| lower.contains(flag))))
        || (has_word(&words, &["iex", "invoke-expression"]) && downloads(&lower));
    if piped_into_shell(&downloads) || fed {
        reasons.push("runs a downloaded script");
    }
    let decodes = |text: &str| {
        ["base64 -d", "base64 --decode", "base64 -D", "xxd -r", "openssl enc -d", "openssl base64 -d"]
            .iter()
            .any(|pattern| text.contains(&pattern.to_ascii_lowercase()))
    };
    if piped_into_shell(&decodes) {
        reasons.push("decodes text into a shell");
    }
    let encoded = has_word(&words, &["powershell", "pwsh"])
        && words
            .iter()
            .any(|word| word.len() >= 2 && word.starts_with("-e") && "-encodedcommand".starts_with(word.as_str()));
    let applescript = lower.contains("osascript") && lower.contains("do shell script");
    if encoded || applescript {
        reasons.push("runs a hidden command");
    }
    if secrets(&lower) {
        reasons.push("reads secrets");
    }
    if sends(&tokens(&line.replace('\\', "/"))) {
        reasons.push("sends a file to a host");
    }
    reasons
}

fn secrets(lower: &str) -> bool {
    const PATHS: [&str; 24] = [
        "~/.ssh",
        "$home/.ssh",
        ".ssh/",
        "id_rsa",
        "id_ed25519",
        "id_ecdsa",
        ".aws/credentials",
        "find-generic-password",
        "find-internet-password",
        "dump-keychain",
        "library/keychains",
        ".keychain-db",
        "google/chrome/",
        "google-chrome/",
        "chromium/default",
        "bravesoftware/",
        "microsoft/edge/user data",
        "firefox/profiles",
        ".mozilla/firefox",
        "cookies.sqlite",
        "wallet.dat",
        "exodus.wallet",
        "ethereum/keystore",
        "nkbihfbeogaeaoehlefnkodbefgpgknn",
    ];
    if PATHS.iter().any(|pattern| lower.contains(pattern))
        || lower.contains(".electrum/")
        || lower.contains("solana/id.json")
    {
        return true;
    }
    let bytes = lower.as_bytes();
    lower.match_indices(".env").any(|(at, _)| {
        let before = at.checked_sub(1).map(|index| bytes[index]);
        let after = bytes.get(at + 4).copied();
        before.is_none_or(|c| !(c.is_ascii_alphanumeric() || c == b'_'))
            && after.is_none_or(|c| !(c.is_ascii_alphanumeric() || c == b'_'))
    })
}

fn sends(words: &[String]) -> bool {
    let named = |index: usize| words[index].rsplit('/').next().unwrap_or(&words[index]).to_ascii_lowercase();
    for index in 0..words.len() {
        let program = named(index);
        let rest = &words[index + 1..];
        match program.as_str() {
            "curl" => {
                for (at, word) in rest.iter().enumerate() {
                    let next = rest.get(at + 1).map(String::as_str).unwrap_or_default();
                    let attached = ["-F", "--form", "-d", "--data", "--data-binary", "--data-urlencode", "--data-raw"]
                        .iter()
                        .any(|flag| {
                            word.starts_with(flag)
                                && word.len() > flag.len()
                                && word[flag.len()..].trim_start_matches('=').contains('@')
                        });
                    let form = matches!(word.as_str(), "-F" | "--form") && next.contains('@');
                    let data = matches!(word.as_str(), "-d" | "--data" | "--data-binary" | "--data-urlencode")
                        && next.starts_with('@');
                    let upload = matches!(word.as_str(), "-T" | "--upload-file");
                    if attached || form || data || upload {
                        return true;
                    }
                }
            }
            "nc" | "ncat" | "netcat" if rest.iter().filter(|word| !word.starts_with('-')).count() >= 2 => return true,
            "scp" | "rsync"
                if rest.iter().any(|word| {
                    !word.starts_with('-')
                        && word.split_once(':').is_some_and(|(host, _)| host.len() > 1 && !host.contains('/'))
                }) =>
            {
                return true
            }
            _ => {}
        }
    }
    false
}
