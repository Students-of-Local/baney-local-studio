#[test]
fn a_marketplace_lists_its_plugins_installs_a_relative_one_and_refuses_npm_and_escapes() {
    let temp = Temp::new();
    let shelf = temp.0.join("shelf");
    marketplace(&shelf);

    let folder = Source::Dir(shelf.clone());
    assert_eq!(entries(&folder).unwrap_or_else(|error| panic!("{error}")), Some(expected_entries()));
    let alpha = resolve(&folder, "alpha").unwrap_or_else(|error| panic!("{error}"));
    assert_eq!(alpha, Source::Dir(shelf.join("plugins/alpha")));
    alpha_installed(&temp.0.join("from-folder"), &alpha);
    let beta = resolve(&folder, "beta").err().unwrap_or_default();
    assert!(beta.contains("beta comes from a npm source, which Local Studio refuses"), "{beta}");
    assert!(resolve(&folder, "gamma").is_err());
    let whole = install(&temp.0.join("whole"), &folder, &empty()).err().unwrap_or_default().join("; ");
    assert!(whole.contains("this is a plugin marketplace, not a plugin; it lists alpha, beta, gamma"), "{whole}");

    let rev = repo(&shelf);
    let url = shelf.to_string_lossy().into_owned();
    let git = Source::Git { url: url.clone(), rev: rev.clone() };
    assert_eq!(entries(&git).unwrap_or_else(|error| panic!("{error}")), Some(expected_entries()));
    let alpha = resolve(&git, "alpha").unwrap_or_else(|error| panic!("{error}"));
    assert_eq!(
        alpha,
        Source::Follow {
            origin: format!("git {url}"),
            url,
            rev,
            subdir: Some("plugins/alpha".to_string()),
            exclude: Vec::new()
        }
    );
    alpha_installed(&temp.0.join("from-git"), &alpha);
    let beta = resolve(&git, "beta").err().unwrap_or_default();
    assert!(beta.contains("npm source, which Local Studio refuses"), "{beta}");
}

