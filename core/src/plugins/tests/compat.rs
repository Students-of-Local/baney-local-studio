fn json_file(path: &Path, value: &Value) {
    write(path, &serde_json::to_string_pretty(value).unwrap_or_else(|error| panic!("{error}")));
}

fn executable(path: &Path, text: &str) {
    write(path, text);
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
        .unwrap_or_else(|error| panic!("chmod {}: {error}", path.display()));
}

fn skill(dir: &Path, name: &str, body: &str) {
    write(
        &dir.join(format!("skills/{name}/SKILL.md")),
        &format!("---\nname: {name}\ndescription: The {name} skill\n---\n{body}"),
    );
}

fn empty() -> Catalog {
    Catalog::parse("").unwrap_or_else(|error| panic!("{error}"))
}

fn header(manifest: &str) -> String {
    format!("# Generated by Local Studio {} from {manifest}. Do not edit; reinstall instead.\n", crate::VERSION)
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|error| panic!("read {}: {error}", path.display()))
}

fn mode(path: &Path) -> u32 {
    std::fs::metadata(path).unwrap_or_else(|error| panic!("{}: {error}", path.display())).permissions().mode() & 0o777
}

fn translated(root: &Path, source: &Source) -> (Plugin, Translation) {
    let installed = install(root, source, &empty()).unwrap_or_else(|errors| panic!("install {source:?}: {errors:?}"));
    let dir = root.join(&installed.plugin.id);
    let plugin = load(&dir).unwrap_or_else(|errors| panic!("load {}: {errors:?}", dir.display()));
    assert_eq!(installed.plugin.id, plugin.id);
    let translation = report(&dir).unwrap_or_else(|| panic!("{} was not translated", dir.display()));
    (plugin, translation)
}

fn launcher(plugin: &Plugin) -> Option<String> {
    let path = plugin.dir.join(LAUNCHER);
    path.exists().then(|| read(&path))
}

fn found(findings: &[Finding]) -> Vec<(String, usize, String)> {
    findings.iter().map(|finding| (finding.file.clone(), finding.line, finding.what.clone())).collect()
}

fn claude_plugin(dir: &Path) {
    json_file(
        &dir.join(".claude-plugin/plugin.json"),
        &json!({"name": "Demo Tools", "version": "1.2.0", "description": "Tools for the demo"}),
    );
    skill(dir, "greet", "Greet the person by name.\n");
    write(&dir.join("commands/review.md"), "---\ndescription: Review the diff\n---\nReview $ARGUMENTS with care.\n");
    write(&dir.join("commands/status.md"), "---\ndescription: Show status\n---\nCurrent state: !`git status`\n");
    json_file(
        &dir.join(".mcp.json"),
        &json!({"mcpServers": {"demo": {
            "command": "node",
            "args": ["${CLAUDE_PLUGIN_ROOT}/server.js"],
            "env": {"API_KEY": "${DEMO_KEY}", "DATA_DIR": "${CLAUDE_PLUGIN_DATA}", "MODE": "fast"}
        }}}),
    );
    write(&dir.join("server.js"), "console.log('demo');\n");
    json_file(
        &dir.join("hooks/hooks.json"),
        &json!({"hooks": {"PostToolUse": [{"matcher": "Write", "hooks": [
            {"type": "command", "command": "${CLAUDE_PLUGIN_ROOT}/scripts/fmt.sh"}
        ]}]}}),
    );
    executable(&dir.join("scripts/fmt.sh"), "#!/bin/sh\nexit 0\n");
    write(&dir.join("agents/reviewer.md"), "---\nname: reviewer\ndescription: Reviews code\n---\nReview.\n");
    executable(&dir.join("bin/helper"), "#!/bin/sh\necho help\n");
}

#[test]
fn a_claude_code_plugin_translates_into_skills_commands_and_one_launched_server() {
    let temp = Temp::new();
    let source = temp.0.join("demo-tools");
    claude_plugin(&source);
    let root = temp.0.join("plugins");
    let (plugin, translation) = translated(&root, &Source::Dir(source.clone()));

    assert_eq!(plugin.id, "demo-tools");
    assert_eq!(translation.kind, Kind::ClaudeCode);
    assert_eq!(
        read(&plugin.dir.join("plugin.toml")),
        header(".claude-plugin/plugin.json")
            + "id = \"demo-tools\"\nname = \"Demo Tools\"\nversion = \"1.2.0\"\ndescription = \"Tools for the demo\"\n"
            + "skills = \"skills\"\ncapabilities = [\"mcp-server\"]\n\n"
            + "[[commands]]\nname = \"review\"\ndescription = \"Review the diff\"\nprompt = \"commands/review.md\"\n\n"
            + "[[commands]]\nname = \"status\"\ndescription = \"Show status\"\nprompt = \"commands/status.md\"\n\n"
            + "[mcp]\ncommand = \".local-studio/mcp\"\nenv = { API_KEY = \"LOCAL_STUDIO_PLUGIN_DEMO_TOOLS__DEMO_KEY\" }\n"
    );
    assert_eq!(
        launcher(&plugin).as_deref(),
        Some(
            "#!/bin/sh\nroot=$(CDPATH= cd -- \"$(dirname -- \"$0\")/..\" && pwd -P) || exit 1\n\
             data=$(CDPATH= cd -- \"$root/../..\" && pwd -P)/plugin-data/demo-tools || exit 1\n\
             mkdir -p \"$data\" || exit 1\n\
             export DATA_DIR=\"$data\"\nexport MODE='fast'\n\
             exec 'node' \"$root\"'/server.js' \"$@\"\n"
        )
    );
    assert_eq!(mode(&plugin.dir.join(LAUNCHER)), 0o755);
    assert_eq!(mode(&plugin.dir.join("scripts/fmt.sh")), 0o644);
    assert_eq!(mode(&plugin.dir.join("bin/helper")), 0o755);
    assert_eq!(
        translation.not_used,
        vec![
            "hook PostToolUse in hooks/hooks.json runs `${CLAUDE_PLUGIN_ROOT}/scripts/fmt.sh`: Local Studio never runs hooks",
            "agent agents/reviewer.md: Local Studio does not use Claude Code agents",
            "bin/helper: Claude Code puts it on the PATH; Local Studio does not",
        ]
    );
    assert_eq!(
        found(&translation.findings),
        vec![(
            "commands/status.md".to_string(),
            4,
            "runs `git status` in Claude Code; Local Studio sends it as text".to_string()
        )]
    );
    assert!(text_findings(&plugin).is_empty());
    assert_eq!(plugin.capabilities, vec![Capability::McpServer]);
    assert_eq!(plugin.skills.len(), 1);
    assert_eq!(plugin.commands.len(), 2);
    let mcp = plugin.mcp.as_ref().unwrap_or_else(|| panic!("no [mcp]"));
    assert_eq!(mcp.command, plugin.dir.join(LAUNCHER));
    assert!(mcp.args.is_empty());

    let fresh = temp.0.join("fresh");
    let Offer::Ask(pending) =
        offer_source(&fresh, &Source::Dir(source), "t".to_string()).unwrap_or_else(|error| panic!("{error}"))
    else {
        panic!("a translated plugin installed without a sheet");
    };
    let request = pending.request();
    assert_eq!(
        request.translated.as_deref(),
        Some("A Claude Code plugin, translated by Local Studio from .claude-plugin/plugin.json")
    );
    assert_eq!(request.not_used, translation.not_used);
    assert_eq!(
        request.findings,
        vec![
            "executable not named in the manifest: bin/helper".to_string(),
            "commands/status.md:4: runs `git status` in Claude Code; Local Studio sends it as text".to_string(),
        ]
    );
    let scopes: Vec<&str> = request.rows.iter().map(|row| row.scope.as_str()).collect();
    assert_eq!(
        scopes,
        vec!["Starts .local-studio/mcp (from .mcp.json: node ${CLAUDE_PLUGIN_ROOT}/server.js) when a thread uses it."]
    );
}

